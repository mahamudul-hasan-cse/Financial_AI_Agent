"""DDL shared by persistence.py and scripts/migrate_sqlite_to_postgres.py."""

_SQLITE_SCHEMA = """
    CREATE TABLE IF NOT EXISTS sessions (
        session_id TEXT PRIMARY KEY,
        client_id TEXT,
        title TEXT NOT NULL DEFAULT 'New research',
        created_at REAL NOT NULL,
        updated_at REAL NOT NULL,
        last_active REAL NOT NULL
    );

    CREATE TABLE IF NOT EXISTS messages (
        id INTEGER PRIMARY KEY AUTOINCREMENT,
        session_id TEXT NOT NULL,
        role TEXT NOT NULL,
        content TEXT NOT NULL,
        timestamp REAL NOT NULL,
        nlp_metadata_json TEXT,
        structured_response_json TEXT,
        FOREIGN KEY (session_id) REFERENCES sessions (session_id) ON DELETE CASCADE
    );

    CREATE TABLE IF NOT EXISTS watchlist (
        session_id TEXT NOT NULL,
        symbol TEXT NOT NULL,
        created_at REAL NOT NULL,
        PRIMARY KEY (session_id, symbol),
        FOREIGN KEY (session_id) REFERENCES sessions (session_id) ON DELETE CASCADE
    );

    CREATE TABLE IF NOT EXISTS alerts (
        id INTEGER PRIMARY KEY AUTOINCREMENT,
        session_id TEXT NOT NULL,
        symbol TEXT NOT NULL,
        alert_type TEXT NOT NULL,
        threshold REAL,
        label TEXT NOT NULL,
        enabled INTEGER NOT NULL DEFAULT 1,
        created_at REAL NOT NULL,
        last_triggered_at REAL,
        last_price REAL,
        FOREIGN KEY (session_id) REFERENCES sessions (session_id) ON DELETE CASCADE
    );

    CREATE INDEX IF NOT EXISTS idx_messages_session_time
    ON messages (session_id, timestamp);

    CREATE INDEX IF NOT EXISTS idx_alerts_session
    ON alerts (session_id);
"""

# DOUBLE PRECISION (not REAL/float4) keeps epoch timestamps exact.
